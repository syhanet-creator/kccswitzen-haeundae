/** 문자표: 유니코드 구간에서 실제 쓸 수 있는 문자만 뽑아 분류별로 보여준다. */
type Range = [number, number];

// 배정되지 않은 코드, 제어·서식·공백·사용자 영역 문자는 제외한다.
const BAD = /[\p{Cn}\p{Cc}\p{Cf}\p{Zs}\p{Zl}\p{Zp}\p{Co}\p{Cs}\p{M}]/u;

const fromRanges = (ranges: Range[], extra = "") => {
  const out: string[] = [];
  for (const [a, b] of ranges) {
    for (let c = a; c <= b; c++) {
      const ch = String.fromCodePoint(c);
      if (!BAD.test(ch)) out.push(ch);
    }
  }
  for (const ch of [...extra]) if (!/\s/.test(ch)) out.push(ch);
  return [...new Set(out)];
};

export type SymbolGroup = { id: string; name: string; chars: () => string[] };

const lazy = (ranges: Range[], extra = "") => {
  let cache: string[] | null = null;
  return () => (cache ??= fromRanges(ranges, extra));
};

